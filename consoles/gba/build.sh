#!/usr/bin/env bash
# Builds the GBA ROM inside Docker.
#   CA_SECRET   shared secret, must match OFFLINE_CODE_SECRET on the server
#   CA_BASE_URL URL printed in the QR code, uppercase, ending in /G/
# Both fall back to the example values, which only work against a server
# running with the example secret.
set -euo pipefail
cd "$(dirname "$0")"

CA_SECRET="${CA_SECRET:-example-secret-change-me}"
CA_BASE_URL="${CA_BASE_URL:-HTTPS://CA.CRAFTER.RUN/G/}"
CA_DISPLAY_URL="${CA_DISPLAY_URL:-ca.crafter.run/g}"
IMAGE="clerk-anywhere-gba"

mkdir -p include
cat > include/ca_config.h <<EOF
// Generated by build.sh. Not committed: it holds the shared secret.
#ifndef CA_CONFIG_H
#define CA_CONFIG_H
#define CA_SECRET "${CA_SECRET}"
#define CA_BASE_URL "${CA_BASE_URL}"
#define CA_DISPLAY_URL "${CA_DISPLAY_URL}"
#endif
EOF

docker build -q -t "$IMAGE" . >/dev/null
MSYS_NO_PATHCONV=1 docker run --rm -v "$(pwd -W 2>/dev/null || pwd):/work" "$IMAGE" \
  make -j"$(nproc 2>/dev/null || echo 4)" "$@"
